                    <h3>🌐 API TikTok officielle</h3>
                    <p>TikCapture utilise les endpoints publics de l'API TikTok de manière responsable et éthique. Nous respectons toutes les limites de taux, n'accédons qu'aux contenus publics, et ne collectons aucune donnée personnelle des utilisateurs. Notre système s'adapte automatiquement aux changements de l'API pour garantir un service toujours fonctionnel.</p>
                </div>
                <div class="technical-card">
                    <h3>🔐 Système de tokens sécurisés</h3>
                    <p>Chaque demande de téléchargement génère un token SHA-256 unique basé sur l'URL de la vidéo, le nom de domaine du serveur, et l'horodatage du jour. Ce token est valide uniquement pour cette vidéo et expire après 24 heures. Cette architecture empêche les accès non autorisés, le hotlinking abusif, et protège notre infrastructure contre les attaques.</p>
                </div>
                <div class="technical-card">
                    <h3>⚡ Téléchargement optimisé</h3>
                    <p>Plutôt que de stocker les vidéos sur nos serveurs (ce qui serait illégal et consommerait énormément d'espace), TikCapture génère des liens de téléchargement direct depuis les serveurs CDN de TikTok. Cela garantit la vitesse maximale, réduit notre charge serveur, et respecte les droits d'auteur en ne créant jamais de copies permanentes.</p>
                </div>
                <div class="technical-card">
                    <h3>🎯 Détection multi-qualité</h3>
                    <p>Notre parser analyse les différents profils de débit (bitrate_info) fournis par TikTok. Selon la vidéo, nous pouvons détecter jusqu'à 6 qualités différentes, chacune avec sa propre résolution, taille de fichier, et URL de téléchargement. L'utilisateur peut ainsi choisir le meilleur compromis entre qualité et taille.</p>
                </div>
                <div class="technical-card">
                    <h3>📡 Parsing HTML et JSON hybride</h3>
                    <p>TikCapture utilise deux méthodes complémentaires : l'extraction des données depuis le HTML de la page TikTok (méthode robuste mais limitée) et les appels directs à l'API JSON (méthode complète mais parfois bloquée). Cette approche hybride garantit que nous obtenons toujours le maximum d'informations disponibles.</p>
                </div>
                <div class="technical-card">
                    <h3>🔄 Système de fallback</h3>
                    <p>Si la méthode principale échoue (URL sans filigrane indisponible, API temporairement inaccessible, vidéo protégée), notre système bascule automatiquement sur des méthodes alternatives : endpoint de secours, extraction depuis downloadAddr plutôt que playAddr, ou utilisation de l'API related_item_list qui fonctionne différemment.</p>
